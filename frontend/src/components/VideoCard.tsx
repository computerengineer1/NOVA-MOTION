/** Video card + library grid: real thumbnails, honest provenance badges,
 *  in-app preview, download, delete (with confirmation), reveal in Explorer. */

import { useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";
import {
  Check, Download, FolderOpen, Play, Trash2, Wand2,
} from "lucide-react";
import { api, thumbnailUrl, videoFileUrl } from "../lib/api";
import { formatBytes, formatDuration } from "../lib/format";
import type { VideoOut } from "../lib/types";
import { Badge, Button, ConfirmDialog, EmptyState } from "./ui";

function aspectLabel(w: number | null, h: number | null): string {
  if (!w || !h) return "";
  const r = w / h;
  if (Math.abs(r - 16 / 9) < 0.05) return "16:9";
  if (Math.abs(r - 9 / 16) < 0.05) return "9:16";
  if (Math.abs(r - 1) < 0.05) return "1:1";
  return `${w}×${h}`;
}

export function ProvenanceBadges({ v, small }: { v: VideoOut; small?: boolean }) {
  const cls = small ? "px-1.5 py-0 text-[9.5px]" : "";
  return (
    <span className="flex flex-wrap items-center gap-1">
      <Badge tone="neutral" className={cls}>{aspectLabel(v.width, v.height)}</Badge>
      <Badge tone={v.interpolated ? "accent" : "ok"} className={cls}
        title={v.interpolated
          ? "Export frame rate is above the model's native rate — in-between frames were estimated by motion interpolation, not generated by the diffusion model"
          : "Exported at the model's native frame rate — every frame was generated, none were invented"}>
        {v.interpolated ? `${v.fps?.toFixed(0)} fps interpolated` : `${v.fps?.toFixed(0)} fps native`}
      </Badge>
      {v.upscaled && (
        <Badge tone="neutral" className={cls}
          title="Lanczos conventional resize — NOT AI super-resolution; no new detail was created">
          upscaled ×2
        </Badge>
      )}
      {v.generation_mode === "multi_shot" && (
        <Badge tone="violet" className={cls} title={v.route_label ?? "Multiple independently sampled segments joined together"}>
          multi-shot
        </Badge>
      )}
    </span>
  );
}

function VideoThumb({ v }: { v: VideoOut }) {
  const [src, setSrc] = useState<string | null>(null);
  useEffect(() => {
    let alive = true;
    let url: string | null = null;
    if (v.thumbnail_url) {
      fetch(thumbnailUrl(v.video_id))
        .then((r) => (r.ok ? r.blob() : null))
        .then((b) => {
          if (alive && b) { url = URL.createObjectURL(b); setSrc(url); }
        })
        .catch(() => {});
    }
    return () => { alive = false; if (url) URL.revokeObjectURL(url); };
  }, [v.video_id, v.thumbnail_url]);

  if (!src) {
    return <div className="grid size-full place-items-center text-faint"><Play size={22} /></div>;
  }
  return <img src={src} alt="" className="size-full object-cover transition duration-300 group-hover:scale-[1.03]" />;
}

export function VideoCard({ v, onDelete, onOpen }: {
  v: VideoOut;
  onDelete: (v: VideoOut) => void;
  onOpen: (v: VideoOut) => void;
}) {
  const navigate = useNavigate();
  const validated = v.status === "COMPLETED" && v.file_exists;

  return (
    <article
      className="group cursor-pointer overflow-hidden rounded-2xl border border-line-soft bg-ink-900/70 transition hover:border-ink-600 focus-ring"
      onClick={() => onOpen(v)}
      role="button" tabIndex={0}
      onKeyDown={(e) => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); onOpen(v); } }}
      aria-label={`Open video: ${v.prompt.slice(0, 60)}`}>
      <div className="relative aspect-video w-full overflow-hidden bg-ink-950">
        <VideoThumb v={v} />
        <div className="pointer-events-none absolute inset-x-0 bottom-0 flex items-end justify-between gap-2 bg-gradient-to-t from-black/80 to-transparent p-2.5">
          <span className="rounded bg-black/60 px-1.5 py-0.5 font-mono text-[10.5px] text-white">
            {formatDuration(v.duration_seconds)}
          </span>
          {validated && (
            <span className="flex items-center gap-1 rounded bg-ok/25 px-1.5 py-0.5 text-[10px] text-ok"
              title="Final duration verified with ffprobe — within ±1 frame of the 8.000 s target">
              <Check size={10} /> validated
            </span>
          )}
        </div>
        <div className="absolute right-2 top-2 flex gap-1 opacity-0 transition group-hover:opacity-100 group-focus-within:opacity-100">
          <a href={videoFileUrl(v.video_id)}
            download={`nova-${v.video_id.slice(0, 8)}.mp4`}
            onClick={(e) => e.stopPropagation()}
            className="grid size-7 place-items-center rounded-lg bg-black/60 text-white hover:bg-accent focus-ring"
            title="Download MP4" aria-label={`Download video ${v.video_id.slice(0, 8)}`}>
            <Download size={13} />
          </a>
          <button onClick={(e) => { e.stopPropagation(); onDelete(v); }}
            className="grid size-7 place-items-center rounded-lg bg-black/60 text-white hover:bg-danger focus-ring"
            title="Delete video" aria-label={`Delete video ${v.video_id.slice(0, 8)}`}>
            <Trash2 size={13} />
          </button>
        </div>
      </div>
      <div className="flex flex-col gap-1.5 p-3">
        <p className="line-clamp-2 min-h-[2.6em] text-xs leading-relaxed text-txt" title={v.prompt}>
          {v.prompt}
        </p>
        <ProvenanceBadges v={v} small />
        <div className="flex items-center gap-2 pt-0.5 text-[10px] text-faint">
          <span>{v.created_at ? new Date(v.created_at).toLocaleDateString() : ""}</span>
          <span>·</span>
          <span className="font-mono">{formatBytes(v.size_bytes)}</span>
          <span>·</span>
          <span className="truncate font-mono">{v.model_id}</span>
          <button className="ml-auto flex shrink-0 items-center gap-1 rounded px-1 py-0.5 text-faint hover:text-accent focus-ring"
            onClick={(e) => { e.stopPropagation(); navigate(`/studio?reuse=${v.generation_id}`); }}
            title="Load this generation's settings into the Studio">
            <Wand2 size={10} /> Reuse
          </button>
        </div>
      </div>
    </article>
  );
}

export function VideoGrid({ videos, onChange }: { videos: VideoOut[]; onChange: () => void }) {
  const [pendingDelete, setPendingDelete] = useState<VideoOut | null>(null);
  const [opening, setOpening] = useState<VideoOut | null>(null);
  const [deleting, setDeleting] = useState(false);

  const doDelete = async () => {
    if (!pendingDelete) return;
    setDeleting(true);
    try {
      await api.deleteVideo(pendingDelete.video_id);
      setPendingDelete(null);
      onChange();
    } finally {
      setDeleting(false);
    }
  };

  return (
    <>
      {videos.length === 0 ? (
        <EmptyState
          icon={<FolderOpen size={30} />}
          title="No videos yet"
          body="Completed generations appear here — each validated to exactly 8.000 s and labeled with its true provenance (native / multi-shot / interpolated / upscaled)."
        />
      ) : (
        <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 xl:grid-cols-3">
          {videos.map((v) => (
            <VideoCard key={v.video_id} v={v} onDelete={setPendingDelete} onOpen={setOpening} />
          ))}
        </div>
      )}

      <ConfirmDialog
        open={!!pendingDelete}
        title="Delete video?"
        confirmLabel={deleting ? "Deleting…" : "Delete file"}
        danger
        onConfirm={doDelete}
        onClose={() => setPendingDelete(null)}
        body={
          <p className="text-sm leading-relaxed text-muted">
            This permanently removes the MP4 and its thumbnail for{" "}
            <span className="font-mono text-txt">{pendingDelete?.video_id.slice(0, 8)}…</span> from
            disk. This cannot be undone.
          </p>
        }
      />

      {opening && (
        <div className="fixed inset-0 z-50 grid place-items-center bg-black/75 p-4"
          onClick={() => setOpening(null)} role="dialog" aria-modal="true" aria-label="Video preview">
          <div className="w-full max-w-3xl" onClick={(e) => e.stopPropagation()}>
            <video src={videoFileUrl(opening.video_id)} controls autoPlay
              className="w-full rounded-xl border border-line bg-black" />
            <div className="mt-3 flex flex-wrap items-center gap-2 rounded-xl border border-line bg-ink-900 p-3">
              <p className="min-w-0 flex-1 text-xs leading-relaxed text-muted" title={opening.prompt}>
                {opening.prompt}
              </p>
              <ProvenanceBadges v={opening} small />
              <Button size="sm" variant="ghost" onClick={() => setOpening(null)}>Close</Button>
            </div>
          </div>
        </div>
      )}
    </>
  );
}
